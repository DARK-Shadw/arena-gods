// Generate src/sim/reach.gen.ts from public/models/*.json: per fighter/move
// strike timing + strike-point samples (character space, metres). The sim uses
// these so hit resolution matches what the animation shows at the strike frame.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const BASE = new Set(['idle','walk','walkBack','strafeL','strafeR','run','block','blockHit','hitFront','hitLeft','hitRight','hitBack','death','getup','crouch','winded','taunt','roar','dodgeBack','dodgeLeft','dodgeRight','fall','land']);
const out = {};
// Moves whose strike is a release/burst, not a reaching contact (keep the speed-peak strike).
const RELEASE = /^(fire_bolt|flame_lash|ember_barrage|falling_star|pyre|snap_shot|quick_draw|twin_shot|heartseeker|pinning_shot|rain_of_thorns|crimson_bolt|seed_spit|cinder_nova|cinder_ward|ward_pulse|howl|dread_roar|quake_stomp|earthshaker|devour|bonfire_night|skullsplitter|scarecrow_spin|tail_sweep|maw_sweep|crushing_leap|.*_feint)$/;
for (const f of readdirSync('public/models').filter((x) => x.endsWith('.json'))) {
  const m = JSON.parse(readFileSync(`public/models/${f}`, 'utf8'));
  out[m.id] = {};
  for (const [k, c] of Object.entries(m.clips)) {
    if (BASE.has(k) || !c.reach) continue;
    // CONTACT strike: for reaching melee moves, the frame where the strike point is
    // farthest forward near the speed peak - that is when the blow visibly lands.
    if (c.speedStrike === undefined) c.speedStrike = c.strike;
    if (!RELEASE.test(k)) {
      const win = c.reach.filter((p) => p[0] >= c.speedStrike - 0.15 && p[0] <= c.speedStrike + 0.25 && p[0] >= c.start + 0.1);
      if (win.length) c.strike = win.reduce((a, b) => (Math.max(b[3], b[6] ?? -9) > Math.max(a[3], a[6] ?? -9) ? b : a))[0];
    } else c.strike = c.speedStrike;
    out[m.id][k] = { start: c.start, strike: c.strike, peaks: c.peaks, dur: c.dur, eff: c.eff, loopActive: c.loopActive, pts: c.reach.map((p) => p.map((v) => +v.toFixed(2))) };
  }
  writeFileSync(`public/models/${f}`, JSON.stringify(m, null, 1));
}
writeFileSync('src/sim/reach.gen.ts', `/* AUTO-GENERATED by tools/convert/gen-reach.mjs from public/models/*.json - do not edit. */\nexport interface ReachClip { start: number; strike: number; peaks: number[]; dur: number; eff: string; loopActive: boolean; pts: number[][] }\nexport const REACH: Record<string, Record<string, ReachClip>> = ${JSON.stringify(out)};\n`);
console.log('[reach] fighters', Object.keys(out).length, 'moves', Object.values(out).reduce((s, x) => s + Object.keys(x).length, 0));
