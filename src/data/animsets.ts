/**
 * Which Mixamo model + clips each fighter uses. Shared by the offline
 * converter (tools/convert) and the runtime animation controller.
 *
 * Paths are relative to the source Assets/ folder. Clip keys are logical
 * names: the base set (idle, walk, run, strafeL/R, walkBack, block,
 * blockHit, hitFront/Left/Right/Back, death, getup, dodgeBack/Left/Right,
 * taunt, roar, winded, crouch, fall, land) plus one clip per sim move id.
 *
 * Move clip options:
 *   start      clip time (s) where the windup begins (skips long lead-ins)
 *   loopActive replay the strike segment for every hit of a multi-hit move
 */
export interface ClipSrc {
  src: string;
  /** Skip the first seconds of the clip (lead-in). */
  start?: number;
  loop?: boolean;
  /** Force the strike-detection effector. */
  eff?: 'RightHand' | 'LeftHand' | 'RightFoot' | 'LeftFoot';
  loopActive?: boolean;
}

export interface AnimSet {
  model: string;
  /** Uniform size multiplier on top of the cm->m conversion (gameplay readability). */
  scale: number;
  clips: Record<string, ClipSrc>;
  /** Has a hand-held weapon mesh; the converter locates its tip for trails. */
  weapon?: boolean;
}

